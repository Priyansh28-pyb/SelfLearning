#using not operator reverse the result
print(not(1==1))
print(not(1==2))

#using and opertor
print((1==1)) and print((1==1))
print(not(1==1)) and print((1==1))
# both condition must be true in this and logical opertor for returing the true

#using or opertor
print((1==1) or (1==1))
print(not(1==1)) or print((1==1))