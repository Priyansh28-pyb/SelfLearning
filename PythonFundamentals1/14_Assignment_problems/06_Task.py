#swaping two numbers entered by the user

num1 = int(input("Enter num 1 :"))
num2 = int(input("Enter num 2 :"))


print("number 1 is : ", num1)
print("number 2 is : ", num2)

print("Numbers after swapping")
num3 = num1
num1 = num2
num2 = num3

print("number 1 is :" ,num1)
print("number 2 is :" ,num2)